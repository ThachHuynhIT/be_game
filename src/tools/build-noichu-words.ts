/**
 * Rebuild `src/noichu/dict/words.ts` (the Nối Chữ dictionary) from Ho Ngoc Duc's Viet74K word list.
 *
 *   curl -o /tmp/Viet74K.txt https://raw.githubusercontent.com/duyet/vietnamese-wordlist/master/Viet74K.txt
 *   npx tsx src/tools/build-noichu-words.ts /tmp/Viet74K.txt
 *
 * Keeps only two-syllable words (the game only chains those): NFC, lower case, letters only (no hyphens or digits),
 * syllables of at most 8 letters and without the letters f j w z (loan words). The result is sorted and de-duplicated.
 * Viet74K is GPL-2.0, see src/noichu/dict/README.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const input = process.argv[2];
if (!input) {
  console.error("usage: tsx src/tools/build-noichu-words.ts <Viet74K.txt>");
  process.exit(1);
}

const words = new Set<string>();
for (const line of readFileSync(input, "utf8").split(/\r?\n/)) {
  const w = line.normalize("NFC").trim().toLowerCase();
  if (!/^\p{L}{1,8} \p{L}{1,8}$/u.test(w) || /[fjwz]/.test(w)) continue;
  words.add(w);
}
const sorted = [...words].sort((a, b) => a.localeCompare(b, "vi"));
const out = join(__dirname, "../noichu/dict/words.ts");
writeFileSync(
  out,
  `// Generated by src/tools/build-noichu-words.ts from Viet74K (Ho Ngoc Duc, GPL-2.0). Do not edit by hand.\n` +
    `// One word per line, two syllables, NFC, lower case. ${sorted.length} words.\n` +
    `export const WORDS_TEXT = ${JSON.stringify(sorted.join("\n"))};\n`,
);
console.log(`${sorted.length} words -> ${out}`);
